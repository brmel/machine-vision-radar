from __future__ import annotations

import json

from ...domain.model.schema import FieldSpec, ModelSchema, TypeSpec

_PRIMITIVES = {"string": "z.string()", "number": "z.number()", "integer": "z.number().int()", "boolean": "z.boolean()"}

def _header(source: str, types: str) -> str:
    return f"""/** DO NOT EDIT: generated by `python -m radar model generate` from {source}. */
import {{ z }} from "zod";
import type * as M from "{types}";

// Jitless: no eval probe under the site's CSP.
z.config({{ jitless: true }});"""

def _named(t: str) -> str:
    return _PRIMITIVES.get(t) or f"z.lazy(() => {t}Schema)"

def _enum(values: tuple[str, ...]) -> str:
    return "z.enum([" + ", ".join(json.dumps(v) for v in values) + "])"

def _zod(f: FieldSpec) -> str:
    if f.type == "enum":
        out = _enum(f.values)
    elif f.type == "array":
        out = f"z.array({_named(f.leaf_type)})" + (f".min({f.min_items})" if f.min_items else "")
    elif f.type == "map":
        out = f"z.record(z.string(), {_named(f.leaf_type)})"
    else:
        out = _named(f.type) + (f".min({f.minimum:g})" if f.minimum is not None else "")
    return out + (".optional()" if f.optional else "")

def _map(t: TypeSpec) -> str:
    item = _named(t.items or "string")
    if t.min_length:
        item += f".refine((s) => s.trim().length >= {t.min_length}, \"must not be empty\")"
    req = ", ".join(f"{k}: {item}" for k in t.required_keys)
    return f"z.object({{ {req} }}).catchall({item})"

def _emit(t: TypeSpec) -> list[str]:
    head = f"export const {t.name}Schema: z.ZodType<M.{t.name}> ="
    if t.kind == "scalar":
        regex = f".regex(new RegExp({json.dumps(t.pattern)}))" if t.pattern else ""
        return ["", f"{head} {_named(t.base or 'string')}{regex};"]
    if t.kind == "enum":
        return ["", f"{head} {_enum(t.values)};"]
    if t.kind == "map":
        return ["", f"{head} {_map(t)};"]
    if t.kind == "union":
        members = ", ".join(f"z.strictObject({{ {v.name}: {_zod(v)} }})" for v in t.variants)
        return ["", f"{head} z.union([{members}]);"]
    body = [f"  {f.name}: {_zod(f)}," for f in t.fields]
    return ["", f"{head} z.strictObject({{", *body, "});"]

def emit_view_zod(schema: ModelSchema) -> str:
    return "\n".join([_header("contracts/model/views.json", "../domain/views.ts"),
                      *(line for t in (*schema.used_by_views(), *schema.views) for line in _emit(t))]) + "\n"
