from __future__ import annotations

from ...domain.model.schema import FieldSpec, ModelSchema, TypeSpec

_PRIMITIVES = {"string": "string", "number": "number", "integer": "number", "boolean": "boolean"}
VIEWS_HEADER = ("/** DO NOT EDIT: generated by `python -m radar model generate` from contracts/model/views.json: the "
                "public read model. */")

def _named(t: str) -> str:
    return _PRIMITIVES.get(t, t)

def _union(values: tuple[str, ...]) -> str:
    return " | ".join(f'"{v}"' for v in values)

def ts_type(f: FieldSpec) -> str:
    if f.type == "enum":
        return _union(f.values)
    if f.type == "array":
        return f"readonly {_named(f.leaf_type)}[]"
    if f.type == "map":
        return f"Readonly<Record<string, {_named(f.leaf_type)}>>"
    return _named(f.type)

def _alias(t: TypeSpec) -> str:
    if t.kind == "scalar":
        return _named(t.base or "string")
    if t.kind == "enum":
        return _union(t.values)
    if t.kind == "map":
        item = _named(t.items or "string")
        return f"Readonly<Record<string, {item}>>" + "".join(f" & {{ readonly {k}: {item} }}" for k in t.required_keys)
    return " | ".join(f"{{ readonly {v.name}: {ts_type(v)} }}" for v in t.variants)

def _emit(t: TypeSpec) -> list[str]:
    doc = f"/** {t.description} */"
    if t.kind not in ("record", "entity"):
        return ["", doc, f"export type {t.name} = {_alias(t)};"]
    body = [f"  readonly {f.name}{'?' if f.optional else ''}: {ts_type(f)};" for f in t.fields]
    return ["", doc, f"export interface {t.name} {{", *body, "}"]

def _emit_entity_kinds(schema: ModelSchema) -> list[str]:
    entries = [f'  {e.name}: {{ prefix: "{e.prefix}", collection: "{e.collection}" }},' for e in schema.entities
               if e.prefix and e.collection]
    return [
        "",
        "export const ENTITY_KINDS = {",
        *entries,
        "} as const;",
        "",
        "export type EntityKind = keyof typeof ENTITY_KINDS;",
        "",
        "const _PREFIX_TO_KIND: Readonly<Record<string, EntityKind>> = Object.fromEntries(",
        "  // Justification (typed boundary): Object.entries widens keys to string; keys are EntityKind.",
        "  Object.entries(ENTITY_KINDS).map(([kind, spec]) => [spec.prefix, kind as EntityKind]),",
        ");",
        "",
        "/** The entity kind an id names, by its prefix. */",
        "export function kindOf(id: string): EntityKind | undefined {",
        '  return _PREFIX_TO_KIND[id.split("_")[0]];',
        "}",
    ]

def emit_view_types(schema: ModelSchema) -> str:
    lines = [VIEWS_HEADER, *(line for t in (*schema.used_by_views(), *schema.views) for line in _emit(t)),
             *_emit_entity_kinds(schema)]
    return "\n".join(lines) + "\n"
