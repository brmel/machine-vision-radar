from __future__ import annotations

from typing import Any

from ...domain.model.schema import PRIMITIVES, FieldSpec, ModelSchema, TypeSpec
from .json_layout import layout

Schema = dict[str, Any]

class _Emitter:
    def __init__(self, schema: ModelSchema) -> None:
        self._schema = schema
        self._used: set[str] = set()

    def _named(self, t: str) -> Schema:
        if t in PRIMITIVES:
            return {"type": t}
        self._used.add(t)
        return {"$ref": f"#/$defs/{t}"}

    def field(self, f: FieldSpec) -> Schema:
        if f.type == "enum":
            out: Schema = {"enum": list(f.values)}
        elif f.type == "array":
            out = {"type": "array", "items": self._named(f.leaf_type),
                   **({"minItems": f.min_items} if f.min_items else {})}
        elif f.type == "map":
            out = {"type": "object", "additionalProperties": self._named(f.leaf_type)}
        else:
            out = {**self._named(f.type), **({"minimum": f.minimum} if f.minimum is not None else {}),
                   **({"format": f.format} if f.format else {})}
        return {**out, **({"description": f.description} if f.description else {}),
                **({"default": f.default} if f.default is not None else {})}

    def record(self, fields: tuple[FieldSpec, ...]) -> Schema:
        return {"type": "object", "properties": {f.name: self.field(f) for f in fields},
                "required": [f.name for f in fields if not f.optional], "additionalProperties": False}

    def of_type(self, t: TypeSpec) -> Schema:
        if t.kind == "scalar":
            return {"type": t.base, **({"pattern": t.pattern} if t.pattern else {})}
        if t.kind == "enum":
            return {"enum": list(t.values)}
        if t.kind == "map":
            item = {**self._named(t.items or "string"), **({"minLength": t.min_length} if t.min_length else {})}
            return {"type": "object", "additionalProperties": item, "required": list(t.required_keys)}
        if t.kind == "union":
            return {"oneOf": [self.record((v,)) for v in t.variants]}
        return self.record(t.fields)

    def defs(self, body: Schema) -> Schema:
        found: dict[str, Schema] = {}
        while missing := sorted(self._used - set(found)):
            for name in missing:
                t = self._schema.types[name]
                found[name] = {"description": t.description, **self.of_type(t)}
        return {**body, **({"$defs": dict(sorted(found.items()))} if found else {})}

def emit_tools(schema: ModelSchema) -> str:
    tools = []
    for tool in schema.tools:
        arguments, answer, output = _Emitter(schema), _Emitter(schema), schema.types[tool.output]
        tools.append({
            "name": tool.name,
            "title": tool.title,
            "description": tool.description,
            "inputSchema": arguments.defs(arguments.record(tool.input.fields)),
            "outputSchema": answer.defs({"description": output.description, **answer.of_type(output)}),
            "annotations": {"readOnlyHint": tool.read_only, "destructiveHint": tool.destructive},
        })
    generated = {"$comment": "DO NOT EDIT: generated by `python -m radar model generate` from "
                             "contracts/model/tools.json.", "tools": tools}
    return layout(generated)
