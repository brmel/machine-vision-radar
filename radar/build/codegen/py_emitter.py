from __future__ import annotations

from ...domain.model.schema import FieldSpec, ModelSchema, TypeSpec, variant_class

_PRIMITIVES = {"string": "str", "number": "float", "integer": "int", "boolean": "bool"}
HEADER = '''"""DO NOT EDIT: generated by `python -m radar model generate` from contracts/model/."""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Literal, Mapping
'''

def _named(t: str) -> str:
    return _PRIMITIVES.get(t, t)

def _literal(values: tuple[str, ...]) -> str:
    return "Literal[" + ", ".join(f'"{v}"' for v in values) + "]"

def _annotation(f: FieldSpec) -> str:
    if f.type == "enum":
        return _literal(f.values)
    if f.type == "array":
        return f"tuple[{_named(f.leaf_type)}, ...]"
    if f.type == "map":
        return f"Mapping[str, {_named(f.leaf_type)}]"
    return _named(f.type)

def _record(name: str, doc: str, fields: tuple[FieldSpec, ...]) -> list[str]:
    lines = ["", "@dataclass(frozen=True, slots=True, kw_only=True)", f"class {name}:", f'    """{doc}"""']
    for f in fields:
        ann = _annotation(f)
        lines.append(f"    {f.name}: {ann} | None = None" if f.optional else f"    {f.name}: {ann}")
    if any(f.name == "next" for f in fields):
        lines += ["", "    @property", "    def cursor(self) -> str | None:", "        return self.next"]
    return lines

def _enum(t: TypeSpec) -> list[str]:
    lines = ["", f"class {t.name}(str, Enum):", f'    """{t.description}"""']
    for v in t.values:
        lines.append(f'    {v.replace("-", "_").upper()} = "{v}"')
    if t.name == "Scope":
        lines += ["", "    def covers(self, needed: Scope) -> bool:", '        """Propose also reads."""',
                  "        return self == needed or needed == Scope.READ"]
    return lines

def _union(t: TypeSpec) -> list[str]:
    lines: list[str] = []
    for v in t.variants:
        lines += _record(variant_class(t.name, v.name), f"{t.name} tagged '{v.name}'.", (v,))
    members = " | ".join(variant_class(t.name, v.name) for v in t.variants)
    return lines + ["", f"# {t.description}", f"{t.name} = {members}"]

def _emit(t: TypeSpec) -> list[str]:
    if t.kind == "scalar":
        return ["", f"# {t.description}", f"{t.name} = {_named(t.base or 'string')}"]
    if t.kind == "enum":
        return _enum(t)
    if t.kind == "map":
        return ["", f"# {t.description}", f"{t.name} = Mapping[str, {_named(t.items or 'string')}]"]
    if t.kind == "union":
        return _union(t)
    return _record(t.name, t.description, t.fields)

def emit_python(schema: ModelSchema) -> str:
    return "\n".join([HEADER.rstrip("\n"),
                      *(line for t in (*schema.value_types, *schema.registry_types, *schema.entities, *schema.views)
                        for line in _emit(t))]) + "\n"
